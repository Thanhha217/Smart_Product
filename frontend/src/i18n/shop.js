/** st("search.count", {n: 3}); lists (e.g. search.examples) come back as arrays. */
export function useShopText() {
  const { lang } = useI18n();
  return useCallback((key, vars) => {
    const entry = S[key];
    if (!entry) return key;
    const v = entry[lang] ?? entry.en;
    if (Array.isArray(v) || !vars) return v;
    return v.replace(/\{(\w+)\}/g, (_, n) => (vars[n] !== undefined && vars[n] !== null ? String(vars[n]) : ""));
  }, [lang]);
}

export function shopText(key, lang = "en") {
  const entry = S[key];
  return entry ? entry[lang] ?? entry.en : key;
}
